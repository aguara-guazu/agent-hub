export type UiLanguage = keyof typeof UI_STRINGS
export type UiStringKey = keyof (typeof UI_STRINGS)["es"]

export function uiLanguage(): UiLanguage {
  const lang = typeof document === "undefined" ? "es" : document.documentElement.lang
  return lang.toLowerCase().startsWith("en") ? "en" : "es"
}

/** Texto del kit en el idioma activo, con `{variable}` reemplazadas. */
export function uiText(key: UiStringKey, vars?: Record<string, string | number>): string {
  const text: string = UI_STRINGS[uiLanguage()][key] ?? UI_STRINGS.es[key]
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}
